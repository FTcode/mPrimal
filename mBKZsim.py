def lembedding_success(K : Cyclotomic, r, m, q, sigma, blocksize_Q, tours, l = 1):
    """
    Success probability model for the l-embedding attack against MLWE (fixed-blocksize BKZ)
    """

    print(blocksize_Q)
    d = K.deg
    c = K.cond

    short_vecs = K.short_vectors_in_l_embedding(l)

    rank_Q = d*(r+m)+l

    vnorm2_pmf = DD12_squarednorm_pmf(d*(r+m), sigma, shift = 0, tol = 0.01)
    success_per_vnorm2 = {vnorm2 : 0 for vnorm2 in vnorm2_pmf.keys()}

    Q_profile = MLWE_initial_Z_shape(K, q, r, m, sigma, embedding = l)
    Q = Cyclotomic(cond=1)

    for tour in range(tours):
        # Run 1 tour of BKZ simulator
        Q_profile = mBKZsim_CN11(Q, Q_profile, tours = 1, blocksize_K = blocksize_Q)

        # Update probabilities
        quantile = exp(Q_profile[-blocksize_Q])

        for vnorm2, p_tot in success_per_vnorm2.items():
            for comb in short_vecs:
                full_norm2 = vnorm2 + sum(zi**2 for zi in comb)*l*sigma**2
                p_new = projected_norm_cdf(rank_Q, sqrt(full_norm2), blocksize_Q, quantile)
                success_per_vnorm2[vnorm2] += (1 - success_per_vnorm2[vnorm2]) * p_new


    sum_result = 0
    for vnorm2, prob in vnorm2_pmf.items():
        sum_result += prob * success_per_vnorm2[vnorm2]

    return sum_result

