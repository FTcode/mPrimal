def mHeurQSlope(K, r):
    d = K.deg
    return -2 * (lghK(K, r) + (log(abs(K.disc))-d*log(d))/(2*d) + avg_lskewness(K, r)) / (d*r - d)

def MLWE_mGSA_pred(K,r,m,q,sigma):
    """
    mGSA prediction for the module primal attack against MLWE
    """
    d = K.deg
    rho = r + m + 1
    ln_det = (rho/2)*log(abs(K.disc)) + m*d*log(q) + d*log(sigma)
    for betaK in range(40//d, r+m+1):
        #lhs = log(sigma * sqrt(d * betaK))
        lhs = log(sigma) + (1/2)*(digamma(d*betaK/2) + log(2))
        rhs = lghK(K, betaK) + ln_det/(d*rho) + ((rho - betaK)/(2*d))*(d**2)*mHeurQSlope(K,betaK)
        if lhs < rhs:
            return betaK
    return None

def MLWE_GSA_pred(K,r,m,q,sigma):
    """
    GSA prediction for the (standard) primal attack against MLWE
    """
    d = K.deg
    rank = d*(r + m) + 1
    ln_vol = (r+m)*log(abs(K.disc))/2 + m*d*log(q) + log(sigma)
    for beta in range(40, d*(r+m+1)):
        ln_alpha = 2*lghZ(beta)/(beta - 1)
        #lhs = log(sigma * sqrt(beta))
        lhs = log(sigma) + (1/2)*(digamma(beta/2) + log(2))
        rhs = ((2*beta - rank - 1)/2)*ln_alpha + ln_vol/rank
        index = rank - beta + 1
        rhs = ((rank+1-2*index)) * lghZ(beta)/(beta - 1) + ln_vol/rank
        if lhs < rhs:
            return beta


def projected_norm_cdf(full_dimension, full_norm, proj_dimension, proj_norm):
    """
    Cumulative density function for the projected norm (proj_norm) when a vector
    in dimension full_dimension, of norm full_norm, is projected onto a random subspace of
    dimension proj_dimension.
    """

    n = full_dimension
    m = proj_dimension
    v = full_norm
    x = proj_norm

    if x <= 0:
        return 0.0
    if x >= v:
        return 1.0

    alpha = m / 2.0
    beta = (n - m) / 2.0
    z = (x / v) ** 2

    return betainc(alpha, beta, z)